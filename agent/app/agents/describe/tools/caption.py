# -*- coding: utf-8 -*-
"""看一张房源照片，写一句图片说明。

## 为什么做这个

`house_images.caption` 这一列**324 条全是空的**。接口一直收 `caption`，
前端 `addHouseImage` 却永远传 `''`，没有任何入口能填它。
顺带 `<img alt>` 也因此一直是空的——读屏软件念到相册那一段，
只有一串「图片、图片、图片」。

房东不填是有道理的：一套房传六张图，让他一张张想一句文案，
这活儿谁都不想干。但让模型写完直接存进去更不行——
**图片说明是挂在房源上给租客看的公开文案**，和标题、描述一个性质。

所以这里只出**草稿**：模型写一句，摆在房东眼前，他改或者不改，
点保存才落库。这条和报修那边「照片读到的那句话要摆在用户眼前」
是同一条规矩，理由也一样：拿一个人没看过的句子替他对外发布，
出了错谁也说不清。

## 和 AI-08 房源描述生成的关系

同一个智能体下面，但**判据完全不同**：

- `compose` + 改写：事实由规则拼好，模型只许润色，改了数字就丢弃；
- 这里：事实**只能来自照片本身**，没有一份「原文」可以对照。

所以约束换了一套写法——不许写照片上看不到的东西（几室几厅、
多少平米、租金、交通、周边），只许写画面里有的。
这几样恰恰是模型最爱补、而且补得最像真的。
"""

from app.llm.base import LLMUnavailable

# 图片说明的长度上限。服务端 `caption[:100]` 会截断，
# 这里要卡得更紧——一句挂在缩略图下面的话，超过 30 个字就没人读了。
MAX_CHARS = 30

_SYSTEM = "你是房屋租赁平台的文案助手。只描述照片里看得见的东西。"

_PROMPT = """给这张房源照片写一句图片说明，挂在缩略图下面给租客看。

**只写照片里看得见的**：房间类型、采光、格局、装修风格、
看得见的家具家电。

**绝对不许写**（这些照片上看不出来，写了就是虚假宣传）：
几室几厅、多少平米、租金、楼层、朝向、几号线地铁、附近有什么学校商场、
房龄、物业、有没有电梯。

一句话，不超过 %d 个字，不要标点符号结尾，不要引号，不要解释。
只输出这一句。""" % MAX_CHARS

# 模型偶尔会把这些词写进来，而它们**一律是从照片上看不出来的**。
# 命中就整句作废：与其给房东一句需要他逐字核对的文案，
# 不如干脆说「没写出来」。
_FORBIDDEN = (
    "室一厅", "室两厅", "平米", "平方", "㎡", "元/月", "月租", "租金",
    "地铁", "公交", "学校", "商场", "医院", "楼层", "朝南", "朝北",
    "电梯", "车位", "学区", "年建", "物业费", "押一付",
)


def draft(images, provider, deadline=None):
    """看图写一句草稿。写不出来就返回空串，**绝不编**。

    识图不可用、模型答非所问、句子里出现了照片上看不出来的东西，
    一律当作「这次没写出来」——房东看到的是一个「再试一次」，
    而不是一句需要他逐字核对的文案。
    """
    urls = [u for u in (images or []) if u][:1]
    if not urls or provider is None:
        return ""
    try:
        text = provider.complete_vision(
            _SYSTEM, _PROMPT, urls, max_tokens=80, deadline=deadline)
    except LLMUnavailable:
        return ""
    except Exception:                                            # noqa: BLE001
        # 写图片说明是纯增强。任何没预料到的错误都不该冒到房东面前
        return ""
    return clean(text)


def clean(text):
    """把模型那一句收拾干净；不合格返回空串。

    单独成函数是为了能脱离模型测边界——模型加引号、加句号、
    写成两行、写了照片上看不出来的东西，都在这里兜住。
    """
    line = ""
    for raw in (text or "").splitlines():
        candidate = raw.strip().strip("*# 　")
        if candidate:
            line = candidate
            break
    if not line:
        return ""

    # 引号、书名号、末尾标点一律去掉：它要贴在缩略图下面，
    # 那个位置上的标点只会显得多余
    line = line.strip("“”\"'「」『』《》 ").rstrip("。.！!～~ ")
    if not line:
        return ""

    # **超长直接作废，不截断。** 截断会把「客厅采光充足，配有」这种
    # 半句话发出去，比没有更难看
    if len(line) > MAX_CHARS:
        return ""

    if any(word in line for word in _FORBIDDEN):
        return ""
    return line
