"""工具：抽出「筛选条件表达不了的那部分需求」（J-09-a 的规则层）。

K-06 的解析器把一句话翻译成筛选条件——区域、户型、租价、设施。
那是**能拿去查数据库的部分**。但人说话时给的信息总是更多：

    「中山区两室一厅，租金三千以内，最好带电梯，
      主要是上班近，周末想看房」
                      └────────┘  └────────┘
                       通勤优先     看房时段

「上班近」不是一个筛选字段（我们没有他公司的坐标），「周末想看房」
更不是——但这两句恰恰是中介接手后最需要知道的：一个决定推哪几套，
一个决定什么时候约。**丢掉它们，中介就只能让租客把刚才的话再说一遍**，
而那正是所有客服系统最招人烦的地方。

所以这一层不查库、不做匹配，只做一件事：把这些「软需求」认出来，
归成固定的几类，好让中介一眼扫过去。

归类同样要**归一化**（和带看纪要那边一个道理）：「上班近」「通勤方便」
「离公司近」是同一件事，落成同一个标签，中介端才好按标签排版。
"""

# 软需求。键是标签，值是说法。
#
# 刻意做得比较窄——**宁可漏，不可错**。这段摘要会原样摆在中介面前，
# 编出一条「有小孩」而实际没有，比少写一条糟得多：
# 中介会照着它推学区房，租客一头雾水。
SOFT_KEYWORDS = [
    ("通勤优先", ["上班近", "通勤", "离公司近", "离单位近", "上下班",
                "地铁沿线", "不想挤"]),
    ("看房时段", ["周末", "周六", "周日", "下班后", "晚上看", "工作日",
                "白天有空", "只有周末"]),
    ("急住", ["急", "尽快", "马上", "这周就", "下周就搬", "越快越好",
             "月底前"]),
    ("长租意向", ["长租", "住一年", "住两年", "稳定", "不想老搬"]),
    ("短租意向", ["短租", "住半年", "住三个月", "过渡"]),
    ("携宠", ["养猫", "养狗", "有宠物", "带猫", "带狗"]),
    ("同住人", ["和女朋友", "和男朋友", "两个人", "一家三口", "带孩子",
              "和父母", "夫妻", "小两口", "合租室友"]),
    ("学区", ["学区", "上学", "孩子读书", "离学校近"]),
    ("停车", ["停车", "车位", "有车"]),
    ("预算可谈", ["可以商量", "多一点也行", "超一点", "灵活"]),
    ("要求安静", ["安静", "不吵", "怕吵", "隔音"]),
    ("拎包入住", ["拎包", "家具齐全", "有家电", "不想买家具"]),
]


def extract(text):
    """从原话里抽出软需求标签。

    返回 ``{"soft": [标签], "matched": [(标签, 命中的词)]}``。
    `matched` 是给答辩用的：能当场说清「这条是从哪个词判出来的」。
    """
    text = (text or "").strip()
    if not text:
        return {"soft": [], "matched": []}

    soft, matched = [], []
    for label, words in SOFT_KEYWORDS:
        hit = next((w for w in words if w in text), None)
        if hit and label not in soft:
            soft.append(label)
            matched.append((label, hit))
    return {"soft": soft, "matched": matched}


# 硬条件的中文标签。摘要里要写给人看，不能直接把 `zujia_max` 摆出去
HARD_LABELS = {
    "suozaidiqu": "区域",
    "fangwuhuxing": "户型",
    "zujia_min": "租金下限",
    "zujia_max": "租金上限",
    "mianji_min": "面积下限",
    "mianji_max": "面积上限",
    "zulinfangshi": "租赁方式",
    "chaoxiang": "朝向",
    "louceng": "楼层",
}

# 带单位的字段。少了单位，「3000」和「80」在一行里分不清是钱还是平米
HARD_UNITS = {"zujia_min": "元", "zujia_max": "元",
              "mianji_min": "㎡", "mianji_max": "㎡"}


def render_hard(filters, features):
    """把筛选条件渲染成一行人话。

    这一行是摘要里**最不该出错**的部分——中介会照着它去挑房源。
    所以它完全由规则拼，不经过大模型：数字原样搬运，一个字都不改写。
    """
    parts = []
    for key, label in HARD_LABELS.items():
        value = (filters or {}).get(key)
        if value in (None, "", 0):
            continue
        unit = HARD_UNITS.get(key, "")
        # 区域、户型这类**值本身就说明了是什么**（「中山区」「两室一厅」），
        # 再加「区域」「户型」前缀只是把一行摘要撑长。
        # 数值型的必须留标签：光写「≤3000元」看不出是租金还是别的
        if key.endswith("_max"):
            parts.append("%s≤%s%s" % (label, value, unit))
        elif key.endswith("_min"):
            parts.append("%s≥%s%s" % (label, value, unit))
        else:
            parts.append(str(value))
    for feature in features or []:
        parts.append(str(feature))
    return " · ".join(parts)
