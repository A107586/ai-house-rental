"""把客服问题分成「事务型」与「知识型」。

**这一步是本功能与「接一个 RAG」最主要的区别。**

「押金一般收几个月」是知识型——答案写在 FAQ 里，全平台用户看到的一样。
「我的押金退了没」是事务型——答案在数据库里，每个用户都不一样。
拿 RAG 去回答第二类问题，模型只能照着 FAQ 的「7 个工作日内退还」编一句
听起来很像样的话，而用户真正想知道的是**他那一笔**到底退没退。
这种回答比拒答有害得多，因为它听上去是有依据的。

所以事务型问题走后端接口取真实数据（并且需要用户令牌），
知识型才走检索。判定要求「业务对象」加上以下任意一种指向自己的信号：

- **人称标记**：「我的」「本人」——最常见的一种
- **显式查询语**：「还差多少」「到哪一步」——省略了人称但显然问的是自己
- **自明词**：「预期收入」「出租率」——这些说法本身就只可能问自己的数据

两者都要有，才不会把「押金一般多久退」误判成「我的押金多久退」；
而三种信号并列，才不会把「预期收入」这种没有人称代词的问法漏掉。

覆盖的事务类型有 13 类，见 `TOPICS`。每一类都对应一个**已有的**后端接口，
一个都不新造——客服能查到的，恰好是用户自己在页面上点得开的那些。
"""

import re

# 人称标记：这句话问的是不是「我自己的」
_PERSONAL = [
    "我的", "我", "本人", "咱的", "俺的", "帮我查", "给我查", "帮我看看",
]

# 业务对象 -> (关键词, 后端取数动作)
# 动作名对应 `account.HANDLERS` 里的函数，加一类事务需要在三处各加一行：
# 这里、`account.HANDLERS`、`toolcall.TOOL_SPECS`。
#
# **顺序即优先级，先匹配到的胜出，所以排列不是随意的。** 三处踩过的坑：
#
# - `handoff` 必须排在 `repair` 前面：「我的转人工工单处理了吗」里的
#   「工单」会被 repair 抢走，答成报修进度。
# - `review` 必须排在 `contract` 前面：「我有哪些租约没评价」里的
#   「租约」会被 contract 抢走，答成租期到期时间。
# - `income` 必须排在 `bill` 前面：「这个月收了多少租金」里的「租金」
#   会被 bill 抢走，可房东问的明明是收入，不是欠费。
#
# 规律是一样的：**含义更窄的排前面**，宽泛的业务名词垫底。
TOPICS = [
    # ---- 含义最窄的几类，必须抢在通用名词前面 ----
    ("handoff", ["转人工", "人工回复", "人工客服回复", "我提交的问题"]),
    ("review", ["评价", "打分", "评分"]),

    # ---- 房东侧（后端会按角色鉴权，这里不做拦截）----
    ("income", ["收入", "收益", "出租率", "经营", "收租", "能收多少",
                "收了多少", "赚了多少", "赚多少", "预期收入", "营收"]),
    ("house", ["我的房源", "我的房子", "我发布", "我挂", "名下房源",
               "名下的房", "房源审核", "我有几套", "上架", "下架"]),
    ("tenant", ["我的租客", "名下租客", "租我房子", "谁在租", "住户是谁"]),

    # ---- 租客侧 ----
    ("bill", ["账单", "房租", "租金", "欠费", "欠多少", "交没交", "缴费",
              "交过", "该交", "要交", "催缴", "逾期"]),
    ("booking", ["预约", "看房申请", "约看"]),
    # 「我租了那些房」一个关键词都不命中，曾被当成知识型问题，
    # 检索回一段缴费说明——答非所问。口语里说「租了哪些」的比
    # 说「我的租约」的多得多。
    ("contract", ["租约", "合同", "租期", "到期", "什么时候到期", "签约",
                  "租了哪些", "租了那些", "我租的", "在租的", "租过哪些",
                  "租了几套", "住的房子"]),
    ("repair", ["报修", "工单", "维修", "修好", "师傅"]),
    ("favorite", ["收藏"]),
    ("history", ["浏览", "看过", "足迹", "浏览记录", "历史记录"]),
    ("message", ["消息", "通知", "站内信", "未读"]),
    ("profile", ["我的账号", "我的资料", "个人信息", "我是什么身份",
                 "我的身份"]),
]

# **自明词**：这些说法本身就只可能问自己的数据，不需要再出现「我的」。
#
# 「预期收入」「出租率」「营收」——没有人会拿这几个词问平台的公共规则，
# 房东说出口就是在问自己名下那几套房。原先一律要求人称标记，
# 结果「预期收入」四个字被判成了知识型问题，去检索 FAQ 自然什么也查不到。
_SELF_EVIDENT = [
    "预期收入", "出租率", "营收", "收了多少", "能收多少", "赚了多少",
    "未读", "足迹", "浏览记录",
]

# 明确指向「查我自己的记录」的说法。命中这些即使没有人称代词也算事务型，
# 比如「账单还差多少没交」——省略了「我的」，但显然问的是自己的。
_EXPLICIT_QUERY = [
    "还差多少", "还欠多少", "欠多少", "退了没", "退了吗", "到哪一步",
    "什么时候到期", "还有几天", "处理好了吗", "通过了吗", "审核过了吗",
    "交到几月", "剩多少",
]

KIND_ACCOUNT = "account"
KIND_KNOWLEDGE = "knowledge"

# 「一般」「通常」这类词把问题拉回知识型：
# 「我的押金一般多久退」问的其实还是规则，不是他那一笔的状态。
_GENERIC = ["一般", "通常", "规定", "政策", "怎么算", "标准是", "都是多久"]

_HANDOFF = ["转人工", "人工客服", "找人工", "真人", "客服电话", "联系客服",
            "找个人问", "人工"]


# 进度询问词。带上这些的句子问的是**已有工单的状态**，不是要新建一张。
#
# 少了这一层会出实打实的问题：「我的转人工工单处理了吗」里有「转人工」
# 三个字，`agent.run()` 先跑 `wants_handoff()`，于是又给用户建了一张
# 新工单——他只是想知道上一张的进度。实测撞到过。
_STATUS_QUERY = [
    "处理了吗", "处理好了吗", "回复了吗", "回了吗", "有结果了吗", "有结果吗",
    "到哪一步", "进度", "怎么样了", "怎样了", "受理了吗", "看了吗",
]


def wants_handoff(text):
    """用户是不是**要求**转人工（而不是在问已有工单的进度）。

    与 `TOPICS` 里的 `handoff` 是一对：这里判断「我要转人工」，
    那边处理「我提交的转人工处理得怎么样了」。
    `agent.run()` 先调这个函数，所以这里必须先把进度询问排除掉，
    否则问进度的人会白白多出一张工单。
    """
    raw = text or ""
    if any(word in raw for word in _STATUS_QUERY):
        return False
    return any(word in raw for word in _HANDOFF)


def classify(text):
    """返回 ``{"kind", "topic", "hits"}``。

    `kind` 为 ``account`` 时 `topic` 指明查哪一类数据；
    为 ``knowledge`` 时 `topic` 为空。
    """
    raw = (text or "").strip()
    if not raw:
        return {"kind": KIND_KNOWLEDGE, "topic": "", "hits": []}

    topic = ""
    hits = []
    for name, keywords in TOPICS:
        matched = [kw for kw in keywords if kw in raw]
        if matched:
            topic, hits = name, matched
            break

    if not topic:
        return {"kind": KIND_KNOWLEDGE, "topic": "", "hits": []}

    # 泛化词把问题拉回知识型
    if any(word in raw for word in _GENERIC):
        return {"kind": KIND_KNOWLEDGE, "topic": "", "hits": hits}

    personal = [word for word in _PERSONAL if word in raw]
    # 问进度本身就隐含「我的」——「人工回复了吗」不会是在问别人的工单，
    # 所以 _STATUS_QUERY 与显式查询语同等看待。
    explicit = [word for word in _EXPLICIT_QUERY + _STATUS_QUERY if word in raw]
    evident = [word for word in _SELF_EVIDENT if word in raw]
    if personal or explicit or evident:
        return {"kind": KIND_ACCOUNT, "topic": topic,
                "hits": hits + personal + explicit + evident}

    return {"kind": KIND_KNOWLEDGE, "topic": "", "hits": hits}
