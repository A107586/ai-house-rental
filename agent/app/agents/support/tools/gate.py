"""可答性闸门（Answerability Gate）。

需求 AI-03 的原话是「知识库中无依据时必须回答『暂无相关信息』，**不得编造**」，
并且给了可量化的指标：无依据问题的拒答率 ≥ 90%。

**这一条靠提示词是保不住的。** 提示词里写「没有依据就说不知道」，
模型照做与否是概率问题；而这里要的是确定性。所以拒答做成代码里的硬闸门，
大模型只能让它更严，不能让它更松。

三条判据：

- **G1 覆盖率**：查询的 IDF 质量有多少落在选中的那一片上（`index.coverage`）
- **G2 关键词命中**：查询里区分度最高的那个词，在选中的材料里出现了吗
  （`index.key_term_hit`）。覆盖率处在中间带时由它拍板。
- **G3 大模型判据**：只在 G1/G2 判定「可答」但覆盖率不算高时才调用，
  且**只能推翻成拒答，不能把拒答改成可答**

G2 是试错换来的。原先用的是「查询里有多少词在整个语料里没出现过」，
两种算法都不成立：算 bigram 太严（任何新说法都会造出没见过的 bigram，
七条本该回答的问题全被拒，而它们的答案还都排在检索第一位），
只算单字又太松（「天气」的天、「发票」的发在租房语料里都是常见字，
拒答率掉到 64%）。结论是**「措辞新不新」不是「答得了答不了」的正确代理量**，
换成「问的那个东西提没提」才对上。

G2 后来又修过一次，坑在「那个东西」怎么挑：原先在字符 bigram 里挑
IDF 最高的，而没见过的组合 IDF 必然最高，于是系统性地挑中「久说」
「扫干」「约完」这种切在词缝上的碎片——不是词，语料里当然没有，
本该回答的问题被拒。改成先用词典判断是不是词，有依据正确率
80% → 85%，拒答率不变。见 `index._key_term_by_word`。

G3 原先只用来「收紧」（把规则的可答改成拒答），现在**反过来了：
只用来翻案，不再否决**。

改的原因是一次实测：检索的 Recall@3 是 100%——**正确答案每次都排在
第一位**——而有依据正确率只有 80%。差的那 20% 全是被 G2 拒掉的，
四条都是很自然的换一种问法：

    「预约完多久房东会确认」「修东西的钱谁出」
    「到期退租有哪些步骤」「退租要打扫干净吗」

材料就在手里、排在第一位，闸门却说「你问的那个词这份资料里没提到」。
用户看到的就是「换个说法它就答不上来了」。

放宽这一侧加了三道约束，拒答率的下限不靠运气：

1. **只在中间带放宽**（`COVER_MIN <= cover < COVER_STRONG` 且关键词未命中）。
   覆盖率低于 `COVER_MIN` 的一律硬拒，大模型碰都不碰。
2. **默认答案是拒。** 大模型不可用、超时、输出不合法——统统维持拒答，
   和改之前一模一样。所以**离线跑出来的指标一个数都不会变**，
   全部离线测试也因此不受影响。
3. 判据提示词写死「资料里直接写明了答案」才算 yes，
   「话题相近但没回答」「要你自己补充知识」都算 no。

至于原先那道「否决」，实测是净负的，已经删掉——理由和数据记在
`evaluate` 里规则放行的那一段上。一句话概括：**域外拒答率在没有它的时候
就已经是 100%**，它买到的东西是零，代价是杀掉三条规则本来答对的问题；
而且它不稳定（同一批问题连跑两次结论不同）又慢（每轮多一次往返）。

所以现在的分工是：**规则说了算，大模型只在规则要拒、而材料其实就在
手里的那一带里，有一次翻案的机会。**
"""

from app.agents.support import corpus
from app.retrieval.tokenize import WORD_LEVEL
from app.llm.base import LLMUnavailable

# 阈值在 `tests/fixtures/support_tune.py` 的调参集上标定，
# **不是在验收集上调的**——验收集全程不参与任何阈值选择。
# 标定脚本：`python -m tests.calibrate_gate`
#
# 覆盖率足够高就直接放行。这一档是为「错别字」和「换个说法」留的：
# 「压金能退吗」的「压」全库不存在，但它靠别名「押金能退吗」
# 拿到 0.65 的覆盖率，该答。
#
# **取值 0.42 是可行区间 [0.41, 0.43] 的中点，不是边缘。** 这一点有代价换来：
# 语料从 54 条扩到 70 条之后，IDF 分布变了，原先定在 0.45 的阈值把一条
# 覆盖率 0.4497 的正例卡在了门外——它的正确答案还排在检索第一位。
# 更糟的是标定脚本当时用 0.05 的粗网格，正好跨过了 0.41~0.43 这段
# **更优且更宽**的平台（回答率 86.2% vs 82.8%，拒答率同为 92.9%）。
#
# 两条教训都写进了标定脚本：网格细到 0.01，并且在可行区间里取中点——
# 取边缘的阈值经不起语料增长，取中点才留得住余量。
#
# **2026-09-13 重标：可行区间变宽成 [0.30, 0.49]，0.42 稳稳在里面，
# 不动。** 变宽不是因为闸门变松了，是因为标定脚本以前算错了——
# 它自己抄了一份规则，而闸门后来加的同义词救场和 G0 它都不知道，
# 于是把一批本该放行的正例算成了拒答，可行区间被压成 [0.30, 0.33]。
# 照那个结果改会把阈值调到 0.32。脚本现在直接调 `evaluate`，不再复述规则。
COVER_STRONG = 0.42
# 覆盖率的绝对下限。标定结果是 0，即不设独立下限——
# 覆盖率低到一定程度时关键词必然也不命中，中间带那一关自会拦下，
# 再叠一道下限只会误伤「那个钱啥时候能回来」这类几乎没有实词的口语问句。
COVER_MIN = 0.0

# 同义替换词的文档频率上限：出现在超过这个比例的片子里，就不算命中证据。
#
# **取 0.16，是可行区间 [0.13, 0.19] 的中点**——和 COVER_STRONG 同一个规矩：
# 取中点不取边缘，边缘的阈值经不起语料增长。
# 标定脚本 `python -m tests.calibrate_gate`，0.01 网格，
# 只在 `tests/fixtures/support_tune.py` 上跑，**验收集全程不参与**。
#
# 这个参数差点标不出来：老的 43 条调参样例里**没有一条走到同义替换**，
# 0.0 到 1.0 整个区间跑出来的两个比率一模一样。调参集标不出来的东西，
# 转头去验收集上扫就是作弊，那条线不能越——所以先往调参集里补了 5 条
# 会走到这条路的样例（3 正 2 负），参数才变得可观测。
#
# 补的负例专挑「同义词是个大路词」的：**「房子」的同义词「房源」
# 在七十片语料里占了十四片**，拿它当「就是这一片」的证据等于没有证据。
# 没有这道门时，「房子能不能做短租」会被放行。
#
# 门槛按文档频率算而不是按 IDF 绝对值：df 比例的含义与语料规模无关
# （「出现在六分之一的片子里」这句话，语料从 70 条涨到 700 条依然成立），
# 而 IDF 的绝对值会跟着整体漂移，按它定的阈值过一阵就不准了。
ALT_DF_MAX = 0.16

_JUDGE_SYSTEM = "你是知识库问答的依据审核员，只输出 JSON，不要解释。"

_JUDGE_PROMPT = """判断下面这些资料能不能回答用户的问题。

用户问题：「{question}」

资料：
{materials}

判断标准：
- 资料里写了问题的答案，**哪怕用词和问题不一样** → yes
  （「维修费用谁承担」回答得了「修东西的钱谁出」，这是同一件事）
- 资料只是话题沾边、并没有回答这个问题 → no
- 要靠你自己的知识补上关键信息才答得了 → no

**判的是「这份资料答不答得了」，不是「措辞像不像」。**
用户换一种说法问同一件事，是最常见的情况，不该因此判 no。

只输出：{{"answerable": "yes 或 no", "why": "不超过20字"}}"""


def _render(index, candidates, limit=3):
    lines = []
    for order, chunk_id in enumerate(candidates[:limit], start=1):
        chunk = index.get(chunk_id)
        if not chunk:
            continue
        lines.append("%d. 【%s】%s" % (order, chunk["title"], chunk["body"]))
    return "\n\n".join(lines)


def evaluate(index, query, candidates, provider=None):
    """判断这次检索的结果够不够回答。

    :param candidates: 精排后的片 id 列表，第一个是最相关的
    :returns: ``{"ok", "reason", "cover", "unseen", "llm", "checked"}``
    """
    result = {"ok": False, "reason": "", "cover": 0.0, "unseen": 0.0,
              "key_term": "", "key_hit": False, "llm": "", "checked": [],
              # 规则本来要拒、被大模型翻过来的那一次。
              # **要能在链路留痕里看见**：答辩时得说清哪些答案是规则放行的、
              # 哪些是模型翻案来的，混在一起就说不清闸门到底严不严
              "rescued": False,
              # 关键词本身没命中、靠同义组命中时，记下命中的是哪一个。
              # 留痕是为了**答辩时说得清这条为什么放行**
              "key_alt": ""}
    if not candidates:
        result["reason"] = "检索没有返回任何候选"
        return result

    # ---- G0：这句话里有没有一个能当话题的词 ----
    #
    # **覆盖率是个比率，分母是查询自己的 IDF 质量。** 查询没什么实质内容
    # 时分母很小，蒙中一两个泛词就能把比率顶到很高。实测：
    #
    #     怎么办    cover 1.000 → 答成「登录状态下在账号设置里可以改密码」
    #     随便      cover 1.000 → 答成「房东怎么入驻」
    #     随便看看   cover 0.511 → 同上
    #     还有别的吗  key_hit=True → 答成「注册时选择身份……」
    #
    # 二十条这类没有实质内容的短句（寒暄、口头禅、导航语），
    # 闸门原样放行十二条，而且每一条都答得像模像样——
    # **比拒答难看得多，用户会以为这系统在胡说**。
    #
    # 判据用现成的 `topic_term`：它在**真词**里挑名词和动词，挑不出来
    # 就说明这句话没有话题。这一条卡在调参集上验过：32 条该答的里
    # 有 2 条会被误伤（「合同能下载下来吗」「约了没去会怎么样」，
    # 分词后只剩「下载」「去」「会」这些够不着门槛的词），
    # 换来十一条不再乱答。**宁可少答两条，不要多编十一条。**
    # **只有装了分词器才问得出这个问题。** 没装 jieba 时
    # `topic_term` 对任何句子都返回空——那不是「这句话没有话题」，
    # 是「这台机器答不了这个问题」。不加这道判断的话，G0 会把
    # **每一个问题**都拒掉。
    #
    # 这个 bug 真的发生了：本机有两个 Python，测试跑在装了 jieba 的那个上
    # （707 条全绿），服务却起在 miniforge 那个上（有 fastapi、没 jieba），
    # 于是线上「押金怎么退」也答不出来，而离线指标是 100%。
    # 补的回归用例见 test_support.TestGateWithoutJieba。
    if WORD_LEVEL and not index.topic_term(query):
        result["reason"] = "问句里没有可检索的话题词"
        return result

    top = candidates[0]
    cover = index.coverage(query, top)
    unseen = index.unseen_ratio(query)
    key_term = index.key_term(query)
    key_hit = index.key_term_hit(query, top)

    # 关键词没命中时，**再拿它的同义组试一次**。
    #
    # 原先同义词表只作用在检索那一侧，于是出现了一个很别扭的局面：
    # 检索靠同义词把正确的那一片排到了第一位，闸门却因为
    # 「你问的『修东西的钱』这片资料里没提到」把它拒了——
    # 而那片资料写的正是「维修费用由谁承担」。
    #
    # 同义词表本来就是为了跨越这种用词差异，**没有理由只用在一半路径上**。
    # 这一条是确定性的：查表，不调模型，不看运气。
    if not key_hit and key_term:
        # **替换词自己得有区分度。**
        #
        # 第一版没有这道门，结果「房子能不能做短租」靠同义词「房源」
        # 命中放行了——而「房源」在 70 片语料里出现在 14 片上，
        # 到处都是。**拿一个到处都有的词当命中证据，等于没有证据。**
        # 拒答率因此从 100% 掉到 90%，正好压在需求下限上。
        #
        # 门槛按文档频率算而不是按 IDF 绝对值：df 比例的含义
        # 和语料规模无关（「出现在五分之一的片子里」这句话，
        # 语料从 70 条涨到 700 条依然成立），IDF 的绝对值会跟着漂。
        for alt in sorted(corpus.synonyms_of(key_term) - {key_term}):
            if not index.key_term_hit_for(alt, top):
                continue
            if index.doc_ratio(alt) > ALT_DF_MAX:
                continue
            key_hit = True
            result["key_alt"] = alt
            break
    result.update({"cover": cover, "unseen": unseen, "key_term": key_term,
                   "key_hit": key_hit, "checked": candidates[:3]})

    if cover < COVER_MIN:
        result["reason"] = "覆盖率 %.2f 低于下限 %.2f" % (cover, COVER_MIN)
        return result

    if cover < COVER_STRONG and not key_hit:
        # 规则判拒。**但先让大模型看一眼材料**——检索的 Recall@3 是 100%，
        # 正确答案就排在第一位，拒掉它的理由只是「问的那个词没在这一片里
        # 出现过」，而换个说法问同一件事本来就不会用同一个词。
        #
        # 翻案前先过一道硬门：**这个词得在整个语料里出现过**。
        #
        # 第一版没有这道门，结果「帮我订个外卖」也被翻了案——它的覆盖率
        # 0.196，而真该救的「到期退租有哪些步骤」是 0.248，两者挨得太近，
        # 阈值定在哪都分不开。换个角度就一目了然：「订」「电影」「健身房」
        # 「机票」在全库一次都没出现过，而「东西」「打扫」「预约」都出现过，
        # 只是不在排第一的那一片里。
        #
        # 道理也站得住：**用户问的那个东西知识库根本没讲过时，
        # 大模型只能靠自己的知识作答**——而 AI-03 禁止的正是这件事。
        can_try = (provider is not None and provider.available
                   and index.term_in_corpus(key_term))
        verdict = _ask_llm(provider, query, _render(index, candidates))             if can_try else ""
        result["llm"] = verdict
        if verdict != "yes":
            result["reason"] = ("覆盖率 %.2f 未达 %.2f，且问的「%s」"
                                "在这份资料里没有提到"
                                % (cover, COVER_STRONG, key_term))
            return result
        result["ok"] = True
        result["rescued"] = True
        result["reason"] = ("覆盖率 %.2f，关键词「%s」未命中，"
                            "但大模型确认资料里写明了答案"
                            % (cover, key_term))
        return result

    # 规则判定可答。**到这里就放行，不再问大模型。**
    #
    # 这里原来还有一道 G3「否决」：中间带的可答结论要再交给大模型复核，
    # 它说 no 就改判拒答。**实测下来这道复核是净负的**——
    #
    #   | 配置              | 域外拒答 | 有依据答上 |
    #   |-------------------|---------|-----------|
    #   | 纯规则            | 100%    | 5/8       |
    #   | 规则 + 大模型否决  | 100%    | 4/8       |
    #
    # 它杀掉了规则本来答对的三条（「预约完多久房东会确认」
    # 「房租能不能晚几天交」「能提前搬走吗」——材料都在手里），
    # 而域外拒答率**在没有它的时候就已经是 100%**：那十条是被覆盖率和
    # 关键词判据拦下的，不是被它拦下的。**它买到的东西是零，代价是三条。**
    #
    # 还有两条一并算进来的账：
    #
    # - 它**不稳定**。同一批问题连跑两次结论不同（「修东西的钱谁出」
    #   上一次翻案、下一次拒答），温度已经压到 0 也一样。
    #   一个用来保证下限的判据本身是概率性的，那就保证不了任何东西。
    # - 它**慢**。每一轮多一次往返，而这正是「智能体反应太慢」的一部分。
    result["ok"] = True
    result["reason"] = ("覆盖率 %.2f，关键词「%s」%s"
                        % (cover, key_term, "命中" if key_hit else "未命中"))
    return result


def _ask_llm(provider, question, materials):
    """返回 ``"yes"`` / ``"no"`` / ``""``（不可用）。

    任何异常都返回空串而不是抛出——大模型不可用时闸门应当退回纯规则结论，
    而不是让整个请求失败（非功能需求 N-07）。
    """
    try:
        data = provider.complete_json(
            _JUDGE_SYSTEM,
            _JUDGE_PROMPT.format(question=question, materials=materials))
    except LLMUnavailable:
        return ""
    except Exception:
        return ""
    if not isinstance(data, dict):
        return ""
    answer = str(data.get("answerable", "")).strip().lower()
    return answer if answer in ("yes", "no") else ""
